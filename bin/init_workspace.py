#!/usr/bin/env python
"""Programmatically initialize topic workspace folders and default templates.
"""

import os
import sys
import argparse
from datetime import date
from pathlib import Path

def create_minimal_index(path: Path, title: str, today: str):
    content = (
        f"# {title} Index\n\n"
        f"> Generated by local llm-wiki lint.\n\n"
        f"Last updated: {today}\n\n"
        f"## Contents\n\n"
        f"| File | Summary | Tags | Updated |\n"
        f"|------|---------|------|---------|\n\n"
        f"## Recent Changes\n\n"
        f"- {today}: Created missing index.\n"
    )
    path.write_text(content, encoding="utf-8")

def main():
    parser = argparse.ArgumentParser(description="Initialize topic workspace")
    parser.add_argument("--topic-dir", default=".", help="Topic directory path (default: current directory)")
    parser.add_argument("--name", default="My Topic", help="Topic name/title")
    parser.add_argument("--scope", default="A topic wiki.", help="Topic scope description")
    args = parser.parse_args()

    topic_path = Path(args.topic_dir).resolve()
    today = date.today().isoformat()

    # 1. Folders to create
    subdirs = [
        "raw",
        "raw/articles",
        "raw/papers",
        "raw/repos",
        "raw/notes",
        "raw/data",
        "wiki",
        "wiki/concepts",
        "wiki/topics",
        "wiki/references",
        "wiki/theses",
        "output",
        "inbox",
        "inbox/.processed"
    ]

    for d in subdirs:
        p = topic_path / d
        p.mkdir(parents=True, exist_ok=True)

    # 2. config.md
    config_content = f"""---
title: "{args.name}"
scope: "{args.scope}"
created: {today}
---

# {args.name}

## Scope

{args.scope}

## Conventions

- Source files go in `raw/` under the appropriate subdirectory
- Compiled articles go in `wiki/references/` (papers) and `wiki/concepts/` (terms)
- All compiled pages use YAML frontmatter and `[[double-bracket]]` concept links
"""
    (topic_path / "config.md").write_text(config_content, encoding="utf-8")

    # 3. log.md
    log_content = f"""# Log

## [{today}] init | Created new topic wiki
"""
    (topic_path / "log.md").write_text(log_content, encoding="utf-8")

    # 4. Root _index.md
    root_index_content = f"""# {args.name}

> Topic wiki initialized on {today}.

## Quick Navigation

| Directory | Purpose |
|-----------|---------|
| [raw/](raw/) | Raw source materials |
| [wiki/](wiki/) | Compiled knowledge base |
| [output/](output/) | Generated artifacts |
| [inbox/](inbox/) | Pending ingestion |

## Statistics

- Raw sources: 0
- Compiled articles: 0
- Concepts: 0
"""
    (topic_path / "_index.md").write_text(root_index_content, encoding="utf-8")

    # 5. Minimal _index.md files for subdirectories
    dir_titles = [
        ("raw", "Raw"),
        ("raw/articles", "Articles"),
        ("raw/papers", "Papers"),
        ("raw/repos", "Repos"),
        ("raw/notes", "Notes"),
        ("raw/data", "Data"),
        ("wiki", "Wiki"),
        ("wiki/concepts", "Concepts"),
        ("wiki/topics", "Topics"),
        ("wiki/references", "References"),
        ("wiki/theses", "Theses"),
        ("output", "Output"),
    ]

    for rel_path, title in dir_titles:
        p = topic_path / rel_path / "_index.md"
        create_minimal_index(p, title, today)

    print(f"Workspace initialized successfully at: {topic_path}")

if __name__ == "__main__":
    main()
