def test_a_pipe_in_a_summary_does_not_tear_the_table(workspace):
    """Only one of the old renderers escaped pipes."""
    _magi(workspace, "wiki", "reindex", ".")
    row = [l for l in _index(workspace).split("\n") if "toric-code.md" in l][0]
    assert r"\|" in row
    assert row.count("|") - row.count(r"\|") == 5


@pytest.mark.parametrize("key", ["updated", "ingested", "created"])
def test_every_dating_convention_is_honoured(tmp_path, key):
    """Ingest routes stamp `ingested`, templates stamp `created`, edits stamp
    `updated`. One renderer read only two of the three, so how a card was
    dated in the table depended on how it had arrived."""
    d = tmp_path / "concepts"
    d.mkdir()
    (d / "a.md").write_text(f"---\ntitle: A\n{key}: 2026-08-01\n---\nx\n",
                            encoding="utf-8")

    assert "2026-08-01" in render_index(d, today="2026-08-26")


def test_categories_appear_only_when_they_separate_something(tmp_path):
    """A Categories list that puts every file under "Uncategorized" is the
    Contents table again wearing a hat."""
    d = tmp_path / "concepts"
    d.mkdir()
    (d / "a.md").write_text("---\ntitle: A\n---\nx\n", encoding="utf-8")
    assert "## Categories" not in render_index(d, today="2026-08-26")

    (d / "b.md").write_text("---\ntitle: B\ncategory: Models\n---\nx\n",
                            encoding="utf-8")
    assert "## Categories" in render_index(d, today="2026-08-26")


def test_reindex_covers_every_wiki_directory_init_creates(workspace):
    """`magi init` scaffolds four; reindex maintained two, so `topics/` and
    `theses/` drifted to whatever lint happened to do to them."""
    _magi(workspace, "wiki", "reindex", ".")
    for name in ("references", "concepts", "topics", "theses"):
        assert (workspace / "wiki" / name / "_index.md").is_file(), name


def test_the_write_is_atomic(tmp_path):
    """`wiki/` is ORIGINAL and the WebUI cancels jobs with `taskkill /F /T`,
    so a half-written index is a real outcome."""
    d = tmp_path / "concepts"
    d.mkdir()
    (d / "a.md").write_text("---\ntitle: A\n---\nx\n", encoding="utf-8")

    assert write_index(d / "_index.md", today="2026-08-26") is True
    assert not list(d.glob(".tmp_atomic_*")), "temp file left behind"
    assert write_index(d / "_index.md", today="2026-08-26") is False
